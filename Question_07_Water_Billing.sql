CREATE OR REPLACE FUNCTION fn_water_charge(p_units NUMERIC)
RETURNS NUMERIC(12,2) LANGUAGE plpgsql AS $$
BEGIN
 IF p_units IS NULL OR p_units<0 THEN RAISE EXCEPTION 'Consumption cannot be NULL or negative'; END IF;
 RETURN (LEAST(p_units,10)*5 + GREATEST(p_units-10,0)*8)::NUMERIC(12,2);
END; $$;

CREATE OR REPLACE FUNCTION fn_validate_reading()
RETURNS TRIGGER LANGUAGE plpgsql AS $$
BEGIN
 IF NEW.current_reading<NEW.previous_reading THEN
  RAISE EXCEPTION 'Current meter reading cannot be below previous reading';
 END IF;
 RETURN NEW;
END; $$;
DROP TRIGGER IF EXISTS trg_validate_reading ON readings;
CREATE TRIGGER trg_validate_reading BEFORE INSERT OR UPDATE ON readings
FOR EACH ROW EXECUTE FUNCTION fn_validate_reading();

CREATE OR REPLACE PROCEDURE pr_generate_bill(p_reading_id BIGINT,p_due_on DATE)
LANGUAGE plpgsql AS $$
DECLARE v_previous NUMERIC(12,2);v_current NUMERIC(12,2);
BEGIN
 SELECT previous_reading,current_reading INTO v_previous,v_current
 FROM readings WHERE reading_id=p_reading_id;
 IF NOT FOUND THEN RAISE EXCEPTION 'Unknown reading ID %',p_reading_id; END IF;
 IF p_due_on IS NULL THEN RAISE EXCEPTION 'Due date cannot be NULL'; END IF;
 IF EXISTS(SELECT 1 FROM bills WHERE reading_id=p_reading_id) THEN RAISE EXCEPTION 'Bill already exists'; END IF;
 INSERT INTO bills(reading_id,charge,amount_paid,due_on)
 VALUES(p_reading_id,fn_water_charge(v_current-v_previous),0,p_due_on);
END; $$;

