CREATE TABLE IF NOT EXISTS customers(customer_id INTEGER PRIMARY KEY,full_name VARCHAR(100) NOT NULL);
CREATE TABLE IF NOT EXISTS readings(
 reading_id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
 customer_id INTEGER NOT NULL REFERENCES customers(customer_id),
 reading_month DATE NOT NULL CHECK(EXTRACT(DAY FROM reading_month)=1),
 previous_reading NUMERIC(12,2) NOT NULL CHECK(previous_reading>=0),
 current_reading NUMERIC(12,2) NOT NULL CHECK(current_reading>=0),
 UNIQUE(customer_id,reading_month)
);
CREATE TABLE IF NOT EXISTS bills(
 bill_id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
 reading_id BIGINT NOT NULL UNIQUE REFERENCES readings(reading_id),
 charge NUMERIC(12,2) NOT NULL CHECK(charge>=0),
 amount_paid NUMERIC(12,2) NOT NULL DEFAULT 0 CHECK(amount_paid>=0 AND amount_paid<=charge),
 due_on DATE NOT NULL
);
CREATE TABLE IF NOT EXISTS receivable_snapshot(
 snapshot_date DATE PRIMARY KEY,total_due NUMERIC(14,2) NOT NULL CHECK(total_due>=0)
);
