CREATE OR REPLACE FUNCTION fn_scholarship_eligible(p_age INTEGER,p_income NUMERIC,p_mark NUMERIC)
RETURNS BOOLEAN LANGUAGE plpgsql AS $$
BEGIN
 IF p_age IS NULL OR p_income IS NULL OR p_mark IS NULL THEN RAISE EXCEPTION 'Eligibility inputs cannot be NULL'; END IF;
 IF p_age<=0 THEN RAISE EXCEPTION 'Age must be positive'; END IF;
 IF p_income<0 THEN RAISE EXCEPTION 'Income cannot be negative'; END IF;
 IF p_mark<0 OR p_mark>100 THEN RAISE EXCEPTION 'Average mark must be between 0 and 100'; END IF;
 RETURN p_age BETWEEN 18 AND 25 AND p_income<=3000 AND p_mark>=70;
END; $$;

CREATE OR REPLACE PROCEDURE pr_assess_application(p_application_id BIGINT)
LANGUAGE plpgsql AS $$
DECLARE v_age INTEGER;v_income NUMERIC;v_mark NUMERIC;v_status VARCHAR(10);
BEGIN
 SELECT age_at_application,monthly_income,average_mark,status
 INTO v_age,v_income,v_mark,v_status
 FROM applications WHERE application_id=p_application_id FOR UPDATE;
 IF NOT FOUND THEN RAISE EXCEPTION 'Unknown application ID %',p_application_id; END IF;
 IF v_status<>'PENDING' THEN RAISE EXCEPTION 'Application % has already been assessed',p_application_id; END IF;
 UPDATE applications SET status=CASE
  WHEN fn_scholarship_eligible(v_age,v_income,v_mark) THEN 'APPROVED'
  ELSE 'REJECTED' END
 WHERE application_id=p_application_id;
END; $$;

CREATE OR REPLACE FUNCTION fn_decision_audit()
RETURNS TRIGGER LANGUAGE plpgsql AS $$
BEGIN
 IF OLD.status IS DISTINCT FROM NEW.status THEN
  INSERT INTO decision_audit(application_id,old_status,new_status)
  VALUES(NEW.application_id,OLD.status,NEW.status);
 END IF;
 RETURN NEW;
END; $$;
DROP TRIGGER IF EXISTS trg_decision_audit ON applications;
CREATE TRIGGER trg_decision_audit AFTER UPDATE ON applications
FOR EACH ROW EXECUTE FUNCTION fn_decision_audit();

