CREATE OR REPLACE VIEW v_approved_applicants AS
SELECT s.student_number,s.full_name,a.average_mark,a.status
FROM applications a JOIN students s USING(student_id)
WHERE a.status='APPROVED';

CREATE INDEX IF NOT EXISTS idx_applications_status_date ON applications(status,submitted_on);
EXPLAIN SELECT application_id,student_id,status FROM applications
WHERE status='PENDING' AND submitted_on BETWEEN CURRENT_DATE-7 AND CURRENT_DATE;

CREATE OR REPLACE PROCEDURE pr_assess_pending()
LANGUAGE plpgsql AS $$
DECLARE a RECORD;
BEGIN
 FOR a IN SELECT application_id FROM applications WHERE status='PENDING' ORDER BY application_id
 LOOP
  CALL pr_assess_application(a.application_id);
 END LOOP;
END; $$;
