CREATE OR REPLACE FUNCTION fn_free_beds(p_room_id INTEGER)
RETURNS INTEGER LANGUAGE plpgsql AS $$
DECLARE v_capacity INTEGER;v_occupied INTEGER;
BEGIN
 SELECT capacity INTO v_capacity FROM rooms WHERE room_id=p_room_id;
 IF NOT FOUND THEN RAISE EXCEPTION 'Unknown room ID %',p_room_id; END IF;
 SELECT COUNT(*) INTO v_occupied FROM allocations WHERE room_id=p_room_id AND status='ACTIVE';
 RETURN v_capacity-v_occupied;
END; $$;

CREATE OR REPLACE FUNCTION fn_validate_allocation()
RETURNS TRIGGER LANGUAGE plpgsql AS $$
DECLARE v_capacity INTEGER;v_occupied INTEGER;v_student_active INTEGER;
BEGIN
 SELECT capacity INTO v_capacity FROM rooms WHERE room_id=NEW.room_id;
 IF NOT FOUND THEN RAISE EXCEPTION 'Unknown room ID %',NEW.room_id; END IF;
 IF NEW.status='ACTIVE' THEN
  SELECT COUNT(*) INTO v_occupied FROM allocations
  WHERE room_id=NEW.room_id AND status='ACTIVE'
   AND allocation_id IS DISTINCT FROM NEW.allocation_id;
  IF v_occupied>=v_capacity THEN RAISE EXCEPTION 'Room is at full capacity'; END IF;
  SELECT COUNT(*) INTO v_student_active FROM allocations
  WHERE student_id=NEW.student_id AND status='ACTIVE'
   AND allocation_id IS DISTINCT FROM NEW.allocation_id;
  IF v_student_active>0 THEN RAISE EXCEPTION 'Student already has an ACTIVE allocation'; END IF;
 END IF;
 RETURN NEW;
END; $$;
DROP TRIGGER IF EXISTS trg_validate_allocation ON allocations;
CREATE TRIGGER trg_validate_allocation BEFORE INSERT OR UPDATE ON allocations
FOR EACH ROW EXECUTE FUNCTION fn_validate_allocation();

CREATE OR REPLACE PROCEDURE pr_allocate_room(p_student_id INTEGER,p_room_id INTEGER,p_allocated_on DATE)
LANGUAGE plpgsql AS $$
BEGIN
 IF NOT EXISTS(SELECT 1 FROM students WHERE student_id=p_student_id) THEN RAISE EXCEPTION 'Unknown student'; END IF;
 IF p_allocated_on IS NULL THEN RAISE EXCEPTION 'Allocation date cannot be NULL'; END IF;
 IF fn_free_beds(p_room_id)<=0 THEN RAISE EXCEPTION 'Room has no free beds'; END IF;
 IF EXISTS(SELECT 1 FROM allocations WHERE student_id=p_student_id AND status='ACTIVE') THEN
  RAISE EXCEPTION 'Student already has an ACTIVE allocation';
 END IF;
 INSERT INTO allocations(student_id,room_id,allocated_on,status) VALUES(p_student_id,p_room_id,p_allocated_on,'ACTIVE');
END; $$;

