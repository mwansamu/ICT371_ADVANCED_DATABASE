CREATE TABLE IF NOT EXISTS students(
 student_id INTEGER PRIMARY KEY,student_number VARCHAR(20) NOT NULL UNIQUE,full_name VARCHAR(100) NOT NULL
);
CREATE TABLE IF NOT EXISTS rooms(
 room_id INTEGER PRIMARY KEY,room_number VARCHAR(20) NOT NULL UNIQUE,capacity INTEGER NOT NULL CHECK(capacity>0)
);
CREATE TABLE IF NOT EXISTS allocations(
 allocation_id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
 student_id INTEGER NOT NULL REFERENCES students(student_id),
 room_id INTEGER NOT NULL REFERENCES rooms(room_id),
 allocated_on DATE NOT NULL,released_on DATE,
 status VARCHAR(10) NOT NULL CHECK(status IN('ACTIVE','ENDED')),
 CHECK((status='ACTIVE' AND released_on IS NULL) OR (status='ENDED' AND released_on IS NOT NULL))
);
CREATE TABLE IF NOT EXISTS occupancy_snapshot(
 snapshot_date DATE NOT NULL,room_id INTEGER NOT NULL REFERENCES rooms(room_id),
 occupied_beds INTEGER NOT NULL,free_beds INTEGER NOT NULL,
 PRIMARY KEY(snapshot_date,room_id)
);
