CREATE OR REPLACE FUNCTION fn_loan_fine(p_loan_id INTEGER,p_as_of DATE)
RETURNS NUMERIC(10,2) LANGUAGE plpgsql AS $$
DECLARE v_due DATE;v_return DATE;v_end DATE;
BEGIN
 SELECT due_on,returned_on INTO v_due,v_return FROM loans WHERE loan_id=p_loan_id;
 IF NOT FOUND THEN RAISE EXCEPTION 'Unknown loan ID %',p_loan_id; END IF;
 IF p_as_of IS NULL THEN RAISE EXCEPTION 'As-of date cannot be NULL'; END IF;
 v_end:=LEAST(p_as_of,COALESCE(v_return,p_as_of));
 RETURN GREATEST(v_end-v_due,0)*2.00;
END; $$;

CREATE OR REPLACE PROCEDURE pr_return_loan(p_loan_id INTEGER,p_returned_on DATE)
LANGUAGE plpgsql AS $$
DECLARE v_borrowed DATE;v_return DATE;
BEGIN
 SELECT borrowed_on,returned_on INTO v_borrowed,v_return FROM loans
 WHERE loan_id=p_loan_id FOR UPDATE;
 IF NOT FOUND THEN RAISE EXCEPTION 'Unknown loan ID %',p_loan_id; END IF;
 IF v_return IS NOT NULL THEN RAISE EXCEPTION 'Loan has already been returned'; END IF;
 IF p_returned_on IS NULL OR p_returned_on<v_borrowed THEN
  RAISE EXCEPTION 'Return date must be on or after borrowed date';
 END IF;
 UPDATE loans SET returned_on=p_returned_on,
 fine_amount=GREATEST(p_returned_on-due_on,0)*2.00 WHERE loan_id=p_loan_id;
END; $$;

CREATE OR REPLACE FUNCTION fn_loan_audit()
RETURNS TRIGGER LANGUAGE plpgsql AS $$
BEGIN
 IF OLD.returned_on IS DISTINCT FROM NEW.returned_on THEN
  INSERT INTO loan_audit(loan_id,old_returned_on,new_returned_on)
  VALUES(NEW.loan_id,OLD.returned_on,NEW.returned_on);
 END IF;
 RETURN NEW;
END; $$;
DROP TRIGGER IF EXISTS trg_loan_audit ON loans;
CREATE TRIGGER trg_loan_audit AFTER UPDATE ON loans
FOR EACH ROW EXECUTE FUNCTION fn_loan_audit();

