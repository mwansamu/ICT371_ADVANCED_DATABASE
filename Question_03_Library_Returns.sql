CREATE TABLE IF NOT EXISTS books(
 book_id INTEGER PRIMARY KEY,title VARCHAR(150) NOT NULL
);
CREATE TABLE IF NOT EXISTS loans(
 loan_id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
 book_id INTEGER NOT NULL REFERENCES books(book_id),
 borrower_name VARCHAR(100) NOT NULL,borrowed_on DATE NOT NULL,due_on DATE NOT NULL,
 returned_on DATE,fine_amount NUMERIC(10,2) NOT NULL DEFAULT 0 CHECK(fine_amount>=0),
 CHECK(due_on>=borrowed_on),
 CHECK(returned_on IS NULL OR returned_on>=borrowed_on)
);
CREATE TABLE IF NOT EXISTS loan_audit(
 audit_id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
 loan_id INTEGER NOT NULL REFERENCES loans(loan_id),
 old_returned_on DATE,new_returned_on DATE,
 changed_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP
);
CREATE TABLE IF NOT EXISTS overdue_summary(
 snapshot_date DATE PRIMARY KEY,overdue_count INTEGER NOT NULL CHECK(overdue_count>=0),
 total_fine NUMERIC(14,2) NOT NULL CHECK(total_fine>=0)
);
