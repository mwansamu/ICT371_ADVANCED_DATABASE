CREATE OR REPLACE FUNCTION fn_maize_rate(p_grade CHAR(1))
RETURNS NUMERIC(8,2) LANGUAGE plpgsql AS $$
BEGIN
 IF p_grade IS NULL THEN RAISE EXCEPTION 'Grade cannot be NULL'; END IF;
 CASE UPPER(p_grade)
  WHEN 'A' THEN RETURN 5.00;
  WHEN 'B' THEN RETURN 4.00;
  WHEN 'C' THEN RETURN 3.00;
  ELSE RAISE EXCEPTION 'Unsupported maize grade %',p_grade;
 END CASE;
END; $$;

CREATE OR REPLACE FUNCTION fn_price_delivery()
RETURNS TRIGGER LANGUAGE plpgsql AS $$
BEGIN
 IF NEW.weight_kg IS NULL OR NEW.weight_kg<=0 THEN RAISE EXCEPTION 'Weight must be positive'; END IF;
 NEW.grade:=UPPER(NEW.grade);
 NEW.unit_rate:=fn_maize_rate(NEW.grade);
 NEW.total_value:=NEW.weight_kg*NEW.unit_rate;
 RETURN NEW;
END; $$;
DROP TRIGGER IF EXISTS trg_price_delivery ON deliveries;
CREATE TRIGGER trg_price_delivery BEFORE INSERT OR UPDATE ON deliveries
FOR EACH ROW EXECUTE FUNCTION fn_price_delivery();

CREATE OR REPLACE PROCEDURE pr_receive_delivery(
 p_farmer_id INTEGER,p_grade CHAR(1),p_weight NUMERIC,p_date DATE)
LANGUAGE plpgsql AS $$
BEGIN
 IF NOT EXISTS(SELECT 1 FROM farmers WHERE farmer_id=p_farmer_id) THEN RAISE EXCEPTION 'Unknown farmer'; END IF;
 IF p_weight IS NULL OR p_weight<=0 THEN RAISE EXCEPTION 'Weight must be positive'; END IF;
 IF p_date IS NULL THEN RAISE EXCEPTION 'Delivery date cannot be NULL'; END IF;
