CREATE TABLE IF NOT EXISTS farmers(
 farmer_id INTEGER PRIMARY KEY,farmer_number VARCHAR(20) NOT NULL UNIQUE,full_name VARCHAR(100) NOT NULL
);
CREATE TABLE IF NOT EXISTS deliveries(
 delivery_id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
 farmer_id INTEGER NOT NULL REFERENCES farmers(farmer_id),
 grade CHAR(1) NOT NULL CHECK(grade IN('A','B','C')),
 weight_kg NUMERIC(12,2) NOT NULL CHECK(weight_kg>0),
 unit_rate NUMERIC(8,2) NOT NULL CHECK(unit_rate>0),
 total_value NUMERIC(14,2) NOT NULL CHECK(total_value>0),
 delivered_on DATE NOT NULL,is_paid BOOLEAN NOT NULL DEFAULT FALSE
);
CREATE TABLE IF NOT EXISTS daily_purchases(
 purchase_date DATE PRIMARY KEY,total_weight NUMERIC(14,2) NOT NULL,total_value NUMERIC(14,2) NOT NULL
);
