CREATE TABLE IF NOT EXISTS vehicles(
 vehicle_id INTEGER PRIMARY KEY,registration VARCHAR(20) NOT NULL UNIQUE,
 current_odometer NUMERIC(12,2) NOT NULL CHECK(current_odometer>=0),
 last_service_odometer NUMERIC(12,2) NOT NULL CHECK(last_service_odometer>=0 AND last_service_odometer<=current_odometer)
);
CREATE TABLE IF NOT EXISTS trips(
 trip_id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
 vehicle_id INTEGER NOT NULL REFERENCES vehicles(vehicle_id),trip_on DATE NOT NULL,
 start_odometer NUMERIC(12,2) NOT NULL,end_odometer NUMERIC(12,2) NOT NULL,
 CHECK(end_odometer>start_odometer)
);
CREATE TABLE IF NOT EXISTS service_alerts(
 vehicle_id INTEGER PRIMARY KEY REFERENCES vehicles(vehicle_id),
 km_since_service NUMERIC(12,2) NOT NULL,flagged_on DATE NOT NULL
);
