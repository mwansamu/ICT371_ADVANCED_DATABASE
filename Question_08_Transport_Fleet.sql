CREATE OR REPLACE FUNCTION fn_service_due(p_vehicle_id INTEGER)
RETURNS BOOLEAN LANGUAGE plpgsql AS $$
DECLARE v_current NUMERIC(12,2);v_last NUMERIC(12,2);
BEGIN
 SELECT current_odometer,last_service_odometer INTO v_current,v_last
 FROM vehicles WHERE vehicle_id=p_vehicle_id;
 IF NOT FOUND THEN RAISE EXCEPTION 'Unknown vehicle ID %',p_vehicle_id; END IF;
 RETURN (v_current-v_last)>=5000;
END; $$;

CREATE OR REPLACE FUNCTION fn_trip_odometer_trigger()
RETURNS TRIGGER LANGUAGE plpgsql AS $$
DECLARE v_current NUMERIC(12,2);
BEGIN
 SELECT current_odometer INTO v_current FROM vehicles
 WHERE vehicle_id=NEW.vehicle_id FOR UPDATE;
 IF NOT FOUND THEN RAISE EXCEPTION 'Unknown vehicle ID %',NEW.vehicle_id; END IF;
 IF NEW.start_odometer<>v_current THEN
  RAISE EXCEPTION 'Trip start must equal vehicle current odometer (%)',v_current;
 END IF;
 IF NEW.end_odometer<=NEW.start_odometer THEN RAISE EXCEPTION 'End odometer must exceed start'; END IF;
 UPDATE vehicles SET current_odometer=NEW.end_odometer WHERE vehicle_id=NEW.vehicle_id;
 RETURN NEW;
END; $$;
DROP TRIGGER IF EXISTS trg_trip_odometer ON trips;
CREATE TRIGGER trg_trip_odometer BEFORE INSERT ON trips
FOR EACH ROW EXECUTE FUNCTION fn_trip_odometer_trigger();

CREATE OR REPLACE PROCEDURE pr_record_trip(
 p_vehicle_id INTEGER,p_trip_on DATE,p_start NUMERIC,p_end NUMERIC)
LANGUAGE plpgsql AS $$
BEGIN
 IF p_trip_on IS NULL THEN RAISE EXCEPTION 'Trip date cannot be NULL'; END IF;
 IF p_end IS NULL OR p_start IS NULL OR p_end<=p_start THEN RAISE EXCEPTION 'Invalid trip mileage'; END IF;
 IF NOT EXISTS(SELECT 1 FROM vehicles WHERE vehicle_id=p_vehicle_id) THEN RAISE EXCEPTION 'Unknown vehicle'; END IF;
 INSERT INTO trips(vehicle_id,trip_on,start_odometer,end_odometer)
 VALUES(p_vehicle_id,p_trip_on,p_start,p_end);
END; $$;

