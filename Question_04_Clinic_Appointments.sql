CREATE TABLE IF NOT EXISTS patients(patient_id INTEGER PRIMARY KEY,full_name VARCHAR(100) NOT NULL);
CREATE TABLE IF NOT EXISTS doctors(doctor_id INTEGER PRIMARY KEY,full_name VARCHAR(100) NOT NULL);
CREATE TABLE IF NOT EXISTS appointments(
 appointment_id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
 patient_id INTEGER NOT NULL REFERENCES patients(patient_id),
 doctor_id INTEGER NOT NULL REFERENCES doctors(doctor_id),
 appointment_day DATE NOT NULL,slot_time TIME NOT NULL,
 status VARCHAR(10) NOT NULL CHECK(status IN('BOOKED','ATTENDED','CANCELLED')),
 CHECK(slot_time IN(TIME '09:00',TIME '10:00',TIME '11:00',TIME '12:00'))
);
CREATE TABLE IF NOT EXISTS clinic_summary(
 summary_date DATE PRIMARY KEY,booked_count INTEGER NOT NULL,
 attended_count INTEGER NOT NULL,cancelled_count INTEGER NOT NULL
);
