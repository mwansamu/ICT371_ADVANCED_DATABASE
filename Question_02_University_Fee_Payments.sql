-- =========================================================
-- PART (e): OUTSTANDING FEE BALANCES VIEW
-- =========================================================

CREATE OR REPLACE VIEW v_fee_balances AS
SELECT
    s.student_number,
    s.full_name,
    fn_fee_balance(s.student_id) AS outstanding_balance
FROM students AS s
WHERE fn_fee_balance(s.student_id) > 0;

